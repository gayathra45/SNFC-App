let currentLanguage: LanguageCode = "en";
const listeners: Array<(lang: LanguageCode) => void> = [];

export async function getStoredLanguage(): Promise<LanguageCode> {
  try {
    const saved = await AsyncStorage.getItem(LANGUAGE_KEY);
    if (saved === "en" || saved === "si" || saved === "ta") {
      currentLanguage = saved;
      return saved;
    }
  } catch {}
  return "en";
}

export async function setStoredLanguage(lang: LanguageCode): Promise<void> {
  currentLanguage = lang;
  try {
    await AsyncStorage.setItem(LANGUAGE_KEY, lang);
  } catch {}
  listeners.forEach((cb) => cb(lang));
}

export function getCurrentLanguage(): LanguageCode {
  return currentLanguage;
}

export function t(key: keyof typeof translations["en"]): string {
  const dict = translations[currentLanguage] || translations["en"];
  return (dict as any)[key] || translations["en"][key] || key;
}

export function onLanguageChange(callback: (lang: LanguageCode) => void): () => void {
  listeners.push(callback);
  return () => {
    const idx = listeners.indexOf(callback);
    if (idx !== -1) listeners.splice(idx, 1);
  };
}
